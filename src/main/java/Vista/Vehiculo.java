    private void configurarTablaRegistros() {
        tablaRegistros.setModel(new javax.swing.table.DefaultTableModel(
                new Object[]{"Placa", "Marca", "Modelo", "Año", "Color", "Propietario"}, 0) {
            @Override public boolean isCellEditable(int fila, int columna) { return false; }
        });
        tablaRegistros.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
        tablaRegistros.getSelectionModel().addListSelectionListener(e -> {
            if (e.getValueIsAdjusting() || tablaRegistros.getSelectedRow() < 0) return;
            int fila = tablaRegistros.convertRowIndexToModel(tablaRegistros.getSelectedRow());
            String placaSeleccionada = String.valueOf(tablaRegistros.getModel().getValueAt(fila, 0));
            Modelo.Vehiculo vehiculoSeleccionado = controlador.buscarVehiculoPorPlaca(placaSeleccionada);
            if (vehiculoSeleccionado == null) { actualizarTablaRegistros(); return; }
            placaT.setText(vehiculoSeleccionado.getPlaca());
            marcaT.setText(vehiculoSeleccionado.getMarca());
            modeloT.setText(vehiculoSeleccionado.getModelo());
            anioT.setText(String.valueOf(vehiculoSeleccionado.getAnio()));
            colorT.setText(vehiculoSeleccionado.getColor());
            actualizarPropietarios();
            if (vehiculoSeleccionado.getPropietario() != null) {
                propietario.setSelectedItem(vehiculoSeleccionado.getPropietario().getCodigo());
            }
        });
        actualizarTablaRegistros();
    }

    private void actualizarTablaRegistros() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaRegistros.getModel();
        modelo.setRowCount(0);
        for (Modelo.Vehiculo vehiculo : controlador.getRepoVehiculos().obtenerTodos()) {
            Modelo.Cliente cliente = vehiculo.getPropietario();
            modelo.addRow(new Object[]{vehiculo.getPlaca(), vehiculo.getMarca(), vehiculo.getModelo(),
                    vehiculo.getAnio(), vehiculo.getColor(), cliente == null ? "" : cliente.getCodigo() + " - " + cliente.getNombreCompleto()});
        }
    }

    private void actualizarPropietarios() {
        String seleccionado = (String) propietario.getSelectedItem();
        javax.swing.DefaultComboBoxModel<String> modelo = new javax.swing.DefaultComboBoxModel<>();
        boolean existeSeleccion = false;
        for (Modelo.Cliente cliente : controlador.getRepoClientes().obtenerTodos()) {
            String codigo = cliente.getCodigo();
            modelo.addElement(codigo);
            if (codigo.equals(seleccionado)) existeSeleccion = true;
        }
        modelo.setSelectedItem(existeSeleccion ? seleccionado : null);
        propietario.setModel(modelo);
    }

    private void guardarActionPerformed(java.awt.event.ActionEvent evt) {
        String placa = placaT.getText().trim().toUpperCase(java.util.Locale.ROOT);
        if (controlador.buscarVehiculoPorPlaca(placa) != null) {
            JOptionPane.showMessageDialog(this, "Ya existe un vehículo con esa placa.");
            return;
        }
        Modelo.Vehiculo vehiculo = leerVehiculo(placa);
        if (vehiculo != null) {
            controlador.registrarVehiculo(vehiculo);
            actualizarTablaRegistros();
            JOptionPane.showMessageDialog(this, "Vehículo guardado exitosamente.");
            limpiarFormulario();
        }
    }

    private Modelo.Vehiculo leerVehiculo(String placa) {
        String marca = marcaT.getText().trim();
        String modelo = modeloT.getText().trim();
        String color = colorT.getText().trim();
        String codigo = (String) propietario.getSelectedItem();
        if (placa.isEmpty() || marca.isEmpty() || modelo.isEmpty() || color.isEmpty() || codigo == null) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos y seleccione un cliente existente.");
            return null;
        }
        Modelo.Cliente cliente;
        try {
            cliente = controlador.buscarClientePorCodigo(codigo);
        } catch (Excepciones.ClienteNoEncontradoException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Cliente no encontrado", JOptionPane.WARNING_MESSAGE);
            return null;
        }
        try {
            int anio = Integer.parseInt(anioT.getText().trim());
            if (anio <= 0) throw new NumberFormatException();
            return new Modelo.Vehiculo(placa, marca, modelo, anio, color, cliente);
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Ingrese un año válido.");
            return null;
        }
    }

    private void buscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buscarActionPerformed
        Modelo.Vehiculo v = controlador.buscarVehiculoPorPlaca(placaT.getText().trim().toUpperCase(java.util.Locale.ROOT));
        if (v == null) {
            JOptionPane.showMessageDialog(this, "No se encontró el vehículo.");
            return;
        }
        marcaT.setText(v.getMarca());
        modeloT.setText(v.getModelo());
        anioT.setText(String.valueOf(v.getAnio()));
        colorT.setText(v.getColor());
        actualizarPropietarios();
        propietario.setSelectedItem(v.getPropietario().getCodigo());
    }//GEN-LAST:event_buscarActionPerformed

    private void listarVehiculosCliente() {
        String codigo = (String) propietario.getSelectedItem();
        if (codigo == null || controlador.getRepoClientes().buscar(codigo) == null) {
            JOptionPane.showMessageDialog(this, "Seleccione un cliente registrado.");
            return;
        }
        java.util.List<Modelo.Vehiculo> vehiculos = controlador.listarVehiculosPorCliente(codigo);
        if (vehiculos.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El cliente no tiene vehículos registrados.");
            return;
        }
        javax.swing.table.DefaultTableModel modeloTabla = new javax.swing.table.DefaultTableModel(
                new Object[]{"Placa", "Marca", "Modelo", "Año", "Color"}, 0) {
            @Override public boolean isCellEditable(int fila, int columna) { return false; }
        };
        for (Modelo.Vehiculo v : vehiculos) {
            modeloTabla.addRow(new Object[]{v.getPlaca(), v.getMarca(), v.getModelo(), v.getAnio(), v.getColor()});
        }
        javax.swing.JTable tabla = new javax.swing.JTable(modeloTabla);
        javax.swing.JScrollPane panel = new javax.swing.JScrollPane(tabla);
        panel.setPreferredSize(new java.awt.Dimension(550, 200));
        JOptionPane.showMessageDialog(this, panel, "Vehículos del cliente " + codigo, JOptionPane.INFORMATION_MESSAGE);
    }

    private void limpiarFormulario() {
        placaT.setText(""); marcaT.setText(""); modeloT.setText("");
        anioT.setText(""); colorT.setText("");
        propietario.setSelectedItem(null);
        placaT.requestFocus();
    }

    private void modificarVehiculo() {
        String placa = placaT.getText().trim().toUpperCase(java.util.Locale.ROOT);
        Modelo.Vehiculo actual = controlador.buscarVehiculoPorPlaca(placa);
        if (actual == null) {
            JOptionPane.showMessageDialog(this, "No se encontró el vehículo.");
            return;
        }
        Modelo.Vehiculo nuevo = leerVehiculo(placa);
        if (nuevo == null) return;
        actual.setMarca(nuevo.getMarca()); actual.setModelo(nuevo.getModelo());
        actual.setAnio(nuevo.getAnio()); actual.setColor(nuevo.getColor());
        actual.setPropietario(nuevo.getPropietario());
        actualizarTablaRegistros();
        JOptionPane.showMessageDialog(this, "Vehículo modificado exitosamente.");
        limpiarFormulario();
    }

    private void eliminarVehiculo() {
        String placa = placaT.getText().trim().toUpperCase(java.util.Locale.ROOT);
        if (controlador.buscarVehiculoPorPlaca(placa) == null) {
            JOptionPane.showMessageDialog(this, "No se encontró el vehículo.");
            return;
        }
        if (JOptionPane.showConfirmDialog(this, "¿Eliminar el vehículo " + placa + "?", "Confirmar", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION) {
            controlador.getRepoVehiculos().eliminar(placa);
            actualizarTablaRegistros();
            limpiarFormulario();
        }
    }

