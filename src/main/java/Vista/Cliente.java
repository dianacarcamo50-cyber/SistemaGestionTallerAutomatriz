    private void configurarTablaRegistros() {
        tablaRegistros.setModel(new javax.swing.table.DefaultTableModel(
                new Object[]{"Código", "Nombre", "Identidad", "Teléfono", "Dirección"}, 0) {
            @Override public boolean isCellEditable(int fila, int columna) { return false; }
        });
        tablaRegistros.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
        tablaRegistros.getSelectionModel().addListSelectionListener(e -> {
            if (e.getValueIsAdjusting() || tablaRegistros.getSelectedRow() < 0) return;
            int fila = tablaRegistros.convertRowIndexToModel(tablaRegistros.getSelectedRow());
            String codigoSeleccionado = String.valueOf(tablaRegistros.getModel().getValueAt(fila, 0));
            Modelo.Cliente clienteSeleccionado = controlador.getRepoClientes().buscar(codigoSeleccionado);
            if (clienteSeleccionado == null) { actualizarTablaRegistros(); return; }
            codigoT.setText(clienteSeleccionado.getCodigo());
            nombreT.setText(clienteSeleccionado.getNombreCompleto());
            idT.setText(clienteSeleccionado.getIdentidad());
            tel.setText(clienteSeleccionado.getTelefono());
            direccionT.setText(clienteSeleccionado.getDireccion());
        });
        actualizarTablaRegistros();
        addWindowFocusListener(new java.awt.event.WindowAdapter() {
            @Override public void windowGainedFocus(java.awt.event.WindowEvent e) { actualizarTablaRegistros(); }
        });
    }

    private void actualizarTablaRegistros() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tablaRegistros.getModel();
        modelo.setRowCount(0);
        for (Modelo.Cliente cliente : controlador.getRepoClientes().obtenerTodos()) {
            modelo.addRow(new Object[]{cliente.getCodigo(), cliente.getNombreCompleto(), cliente.getIdentidad(),
                    cliente.getTelefono(), cliente.getDireccion()});
        }
    }

    private void guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_guardarActionPerformed
        // TODO add your handling code here:
        String codigoStr = codigoT.getText().trim();
    String nombreStr = nombreT.getText().trim();
    String identidadStr = idT.getText().trim();
    String direccionStr = direccionT.getText().trim();

    if (codigoStr.isEmpty() || nombreStr.isEmpty() || identidadStr.isEmpty() || direccionStr.isEmpty() || tel.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, 
            "Por favor, complete código, nombre, identidad, teléfono y dirección.", 
            "Campos Vacíos", 
            JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (verificarSiExisteCodigo(codigoStr)) {
        JOptionPane.showMessageDialog(this, 
            "Ya existe un cliente registrado con el código: " + codigoStr, 
            "Código Duplicado", 
            JOptionPane.ERROR_MESSAGE);
        return;
    }

    Modelo.Cliente cliente = new Modelo.Cliente(codigoStr, nombreStr, identidadStr, tel.getText().trim());
    cliente.setDireccion(direccionStr);
    controlador.getRepoClientes().guardar(codigoStr, cliente);

    actualizarTablaRegistros();
    JOptionPane.showMessageDialog(this, 
        "¡Cliente guardado exitosamente!", 
        "Registro Exitoso", 
        JOptionPane.INFORMATION_MESSAGE);
    
    limpiarFormulario();
    }//GEN-LAST:event_guardarActionPerformed

    private void buscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buscarActionPerformed
        // TODO add your handling code here:
        String codigoStr = codigoT.getText().trim();

    if (codigoStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, 
            "Ingrese el código único del cliente que desea buscar.", 
            "Aviso", 
            JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (controlador.getRepoClientes().existe(codigoStr)) {
        Modelo.Cliente datos = controlador.getRepoClientes().buscar(codigoStr);
        nombreT.setText(datos.getNombreCompleto());
        idT.setText(datos.getIdentidad());
        direccionT.setText(datos.getDireccion());
        tel.setText(datos.getTelefono());
        JOptionPane.showMessageDialog(this, "¡Cliente encontrado con éxito!", "Búsqueda Exitosa", JOptionPane.INFORMATION_MESSAGE);
    } else {
        JOptionPane.showMessageDialog(this, 
            "No se encontró ningún cliente con el código: " + codigoStr, 
            "No Encontrado", 
            JOptionPane.WARNING_MESSAGE);
    }
    }//GEN-LAST:event_buscarActionPerformed

    private void limpiarFormulario() {
        codigoT.setText("");
        nombreT.setText("");
        idT.setText("");
        direccionT.setText("");
        tel.setText("");
    }

    private boolean verificarSiExisteCodigo(String codigo) {
        return controlador.getRepoClientes().existe(codigo);
    }

    private void modificarCliente() {
        String codigo = codigoT.getText().trim();
        if (!controlador.getRepoClientes().existe(codigo)) {
            JOptionPane.showMessageDialog(this, "Ingrese el código de un cliente existente.");
            return;
        }
        String nombre = nombreT.getText().trim();
        String identidad = idT.getText().trim();
        if (nombre.isEmpty() || identidad.isEmpty() || tel.getText().trim().isEmpty() || direccionT.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete el nombre, la identidad, el teléfono y la dirección.");
            return;
        }
        Modelo.Cliente actual = controlador.getRepoClientes().buscar(codigo);
        actual.setNombreCompleto(nombre);
        actual.setIdentidad(identidad);
        actual.setTelefono(tel.getText().trim());
        actual.setDireccion(direccionT.getText().trim());
        actualizarTablaRegistros();
        JOptionPane.showMessageDialog(this, "Cliente modificado exitosamente.");
        limpiarFormulario();
    }

    private void eliminarCliente() {
        String codigo = codigoT.getText().trim();
        if (!controlador.getRepoClientes().existe(codigo)) {
            JOptionPane.showMessageDialog(this, "Ingrese el código de un cliente existente.");
            return;
        }
        if (JOptionPane.showConfirmDialog(this, "¿Eliminar el cliente con código " + codigo + "?",
                "Confirmar eliminación", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION) {
            if (!controlador.listarVehiculosPorCliente(codigo).isEmpty()
                    || controlador.getRepoOrdenes().obtenerTodos().stream()
                        .anyMatch(o -> codigo.equals(o.getCliente().getCodigo()))) {
                JOptionPane.showMessageDialog(this, "No se puede eliminar un cliente con vehículos u órdenes asociados.");
                return;
            }
            controlador.getRepoClientes().eliminar(codigo);
            actualizarTablaRegistros();
            limpiarFormulario();
            JOptionPane.showMessageDialog(this, "Cliente eliminado exitosamente.");
        }
    }

