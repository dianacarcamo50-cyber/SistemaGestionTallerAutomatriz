    private void generarFactura() {
        String ordenId = javax.swing.JOptionPane.showInputDialog(this, "Número de orden finalizada:");
        if (ordenId == null) return;
        Modelo.OrdenTrabajo orden = controlador.getRepoOrdenes().buscar(ordenId.trim());
        if (orden == null || orden.getEstado() != Modelo.OrdenTrabajo.EstadoOrden.FINALIZADA) {
            javax.swing.JOptionPane.showMessageDialog(this, "La orden no existe o no está finalizada."); return;
        }
        for (Modelo.Factura existente : controlador.getRepoFacturas().obtenerTodos()) {
            if (existente.getOrden() == orden) {
                facturaActual = existente;
                subtotal.setText(String.format(java.util.Locale.ROOT, "%.2f", existente.getSubtotalServicios()));
                SubRepuestos.setText(String.format(java.util.Locale.ROOT, "%.2f", existente.getSubtotalRepuestos()));
                total.setText(String.format(java.util.Locale.ROOT, "%.2f", existente.getTotal()));
                impuesto.setText(String.valueOf(existente.getImpuestoPorcentaje()));
                setTitle("Factura " + existente.getNumeroFactura());
                javax.swing.JOptionPane.showMessageDialog(this, existente.isPagada() ? "Factura ya pagada." : "Factura existente cargada.");
                return;
            }
        }
        String numero = javax.swing.JOptionPane.showInputDialog(this, "Número único de factura:");
        if (numero == null) return;
        numero = numero.trim();
        if (numero.isEmpty() || controlador.getRepoFacturas().existe(numero)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un número de factura único."); return;
        }
        try {
            Modelo.Factura nueva = new Modelo.Factura(numero, orden, Double.parseDouble(impuesto.getText().trim()));
            controlador.getRepoFacturas().guardar(numero, nueva); facturaActual = nueva;
            subtotal.setText(String.format(java.util.Locale.ROOT, "%.2f", nueva.getSubtotalServicios()));
            SubRepuestos.setText(String.format(java.util.Locale.ROOT, "%.2f", nueva.getSubtotalRepuestos()));
            total.setText(String.format(java.util.Locale.ROOT, "%.2f", nueva.getTotal()));
            setTitle("Factura " + numero);
        } catch (IllegalArgumentException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un impuesto válido y no negativo.");
        }
    }

    private void pagarFactura() {
        if (facturaActual == null) { javax.swing.JOptionPane.showMessageDialog(this, "Genere una factura primero."); return; }
        if (facturaActual.isPagada()) { javax.swing.JOptionPane.showMessageDialog(this, "La factura ya fue pagada."); return; }
        String monto = javax.swing.JOptionPane.showInputDialog(this, "Monto entregado en efectivo:");
        if (monto == null) return;
        try {
            double cambio = facturaActual.procesarPagoEfectivo(Double.parseDouble(monto.trim()));

            javax.swing.JOptionPane.showMessageDialog(this, String.format(java.util.Locale.ROOT, "Pago recibido. Cambio: %.2f", cambio));
        } catch (Excepciones.PagoInsuficienteException | IllegalArgumentException | IllegalStateException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo procesar el pago: " + ex.getMessage());
        }
    }

